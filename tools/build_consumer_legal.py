"""Publish the same date rules to the browser and versioned terms to email code."""
from pathlib import Path
import json
import re
from html import unescape
ROOT=Path(__file__).resolve().parents[1]
shared=ROOT/'supabase/functions/_shared'
(ROOT/'inspectie-boeken/booking-dates.mjs').write_text('// Generated by tools/build_consumer_legal.py.\n'+(shared/'consumer-dates.mjs').read_text())
for version in ('2026-10-10','2026-10-11','2026-10-11-betalen'):
    terms=(ROOT/f'legal/consumentenboeking-{version}.txt').read_text()
    (shared/f'consumer-terms-{version.replace("-", "")}.mjs').write_text(f'// Generated from legal/consumentenboeking-{version}.txt.\nexport const CONSUMER_TERMS='+json.dumps(terms,ensure_ascii=False)+';\n')
privacy=(ROOT/'privacy.html').read_text().split('<div class="legal-body">',1)[1].split('</div></section>',1)[0]
privacy=re.sub(r'<a[^>]*download[^>]*>.*?</a>','',privacy)
privacy=re.sub(r'</(?:p|h[1-6]|li|ul)>','\n\n',privacy)
privacy=unescape(re.sub(r'<[^>]+>','',privacy))
privacy=re.sub(r'\n\s*\n','\n\n',privacy).strip()
(ROOT/'legal/privacy-2026-10-11.txt').write_text('Privacyverklaring RoofSignal\n\n'+privacy+'\n')
